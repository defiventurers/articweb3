// Verify the Home invitation against the actual private-room service.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';

const mobile=fileURLToPath(new URL('../',import.meta.url));
const require=createRequire(import.meta.url),frontendRequire=createRequire(new URL('../../../frontend/package.json',import.meta.url));
const {chromium}=require(path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES,'playwright'));
const {WebSocketServer}=frontendRequire('ws');
const {createArcticPlayService}=require('../../../server/arcticPlayService.js');
const engine=require('../build/games.cjs');
const out=path.join(mobile,'verification/release-4.9.0/home-invitation');
await fs.mkdir(out,{recursive:true});
const checks=[],errors=[],rooms=new Map();
const send=(socket,packet)=>{if(socket.readyState===1)socket.send(JSON.stringify(packet));};
const service=createArcticPlayService({rooms,send,ok:(socket,requestId,type,payload)=>send(socket,{requestId,type,payload}),fail:(socket,requestId,message)=>send(socket,{requestId,type:'error',payload:{message}})});
const server=http.createServer((req,res)=>{if(!service.handleHttp(req,res))res.writeHead(404).end();});
const sockets=new WebSocketServer({noServer:true});
server.on('upgrade',(req,socket,head)=>sockets.handleUpgrade(req,socket,head,ws=>sockets.emit('connection',ws,req)));
sockets.on('connection',ws=>{ws.on('message',raw=>{const p=JSON.parse(raw);service.dispatch(ws,p.requestId,p.type,p.payload);});ws.on('close',()=>service.disconnected(ws));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+server.address().port;
const packets=[],host={readyState:1,send:text=>packets.push(JSON.parse(text))};
await service.dispatch(host,'home-host','ap_room_create',{tableId:'xiangqi',name:'Host',playerId:'home-invitation-host'});
const created=packets.find(p=>p.requestId==='home-host');
assert.notEqual(created.type,'error');
const code=created.payload.room.roomCode;
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,hasTouch:true,isMobile:true,reducedMotion:'reduce'});
await context.addInitScript(({base,practice})=>{
  const originalFetch=window.fetch.bind(window);
  window.fetch=(input,options)=>originalFetch(typeof input==='string'&&input.startsWith('https://articweb3.onrender.com/')?base+input.slice('https://articweb3.onrender.com'.length):input,options);
  const Original=window.WebSocket;
  window.WebSocket=class extends Original{constructor(url,...rest){super(url==='wss://articweb3.onrender.com'?base.replace('http:','ws:'):url,...rest);}};
  localStorage.setItem('arctic-play.v1.profile',JSON.stringify({id:'home-invitation-guest',name:'Player',avatar:'blue'}));
  localStorage.setItem('arctic-play.v1.theme',JSON.stringify('light'));
  localStorage.setItem('arctic-play.v1.mascot-companions',JSON.stringify({mode:'off',motion:false}));
  localStorage.setItem('arctic-play.v1.practice.xiangqi',JSON.stringify(practice));
  localStorage.setItem('arctic-play.v1.last-table',JSON.stringify({id:'xiangqi'}));
  window.Android={appReady(){},setDarkTheme(){}};
},{base,practice:{id:'xiangqi',state:engine.create('xiangqi'),mode:'hotseat',humans:['red','blue'],history:[],guide:false}});
const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto(base+'/arctic-play/app/');
  await page.locator('.home-world-art').waitFor();
  await page.waitForFunction(()=>document.querySelector('.home-world-art').complete&&document.querySelector('.home-world-art').naturalWidth>0);
  await page.screenshot({path:path.join(out,'home-light.png')});
  await page.getByRole('button',{name:'Explore the Halls',exact:false}).click();
  assert.equal(await page.locator('.hall-card').count(),7);checks.push('The primary Explore the Halls button opens all seven games');
  await page.locator('.bottom-nav').getByRole('button',{name:'Home',exact:true}).click();
  assert.equal(await page.locator('#home-room-code input').count(),6);
  assert.equal(await page.locator('#home-room-code .room-code-hyphen').count(),5);
  assert.equal(await page.locator('.home-world-copy').evaluate(n=>getComputedStyle(n).backgroundColor),'rgba(0, 0, 0, 0)');
  await page.locator('#home-room-code-1').pressSequentially('abc234');
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),'ABC234');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'home-room-code-6');
  await page.locator('#home-room-code-6').press('Backspace');
  await page.locator('#home-room-code-6').press('Backspace');
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),'ABC2');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'home-room-code-5');
  await page.locator('#home-room-code-5').pressSequentially('34');
  await page.locator('#home-room-code-3').press('Delete');
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),'AB 234');
  await page.locator('#home-room-code-3').pressSequentially('c');
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),'ABC234');
  await page.locator('#home-room-code-4').press('ArrowLeft');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'home-room-code-3');
  await page.locator('#home-room-code-3').press('ArrowRight');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'home-room-code-4');
  checks.push('Six single-character boxes and five hyphens support auto-advance, backspace, deletion and arrow keys');
  await page.locator('#home-room-code').evaluate((el,code)=>{const data=new DataTransfer();data.setData('text',code.split('').join('-'));el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,clipboardData:data}));},code);
  checks.push('A hyphenated room code pastes into all six fields');
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),code);
  await page.getByRole('button',{name:'Join friends',exact:true}).click();
  await page.getByRole('dialog',{name:'Your name',exact:true}).waitFor();
  await page.waitForFunction(()=>document.activeElement?.id==='join-name');
  assert.equal(await page.locator('#room-code').count(),0);checks.push('The Home code carries into a focused name-only prompt');
  await page.locator('#join-name').fill('Unsubmitted name');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),code);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('arctic-play.v1.profile')).name),'Player');checks.push('Cancelling preserves the code and does not change the saved name');
  await page.locator('#home-room-code').evaluate((el,code)=>{const data=new DataTransfer();data.setData('text','https://articweb3.onrender.com/arctic-play/app/?room='+code);el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,clipboardData:data}));},code);
  assert.equal(await page.locator('#home-room-code').getAttribute('data-code'),code);
  await page.locator('#home-room-code-6').press('Enter');await page.getByRole('dialog',{name:'Your name',exact:true}).waitFor();checks.push('A pasted invitation and keyboard Go follow the same name-first flow');
  await page.getByRole('button',{name:'Change room',exact:true}).click();
  await page.getByRole('dialog',{name:'Join a room',exact:true}).waitFor();assert.equal(await page.locator('#room-code').getAttribute('data-code'),code);
  await page.getByRole('button',{name:'Close',exact:true}).click();checks.push('The room code can still be edited before joining');
  await page.getByRole('button',{name:'Join friends',exact:true}).click();
  await page.locator('#join-name').fill('   ');assert.equal(await page.getByRole('button',{name:'Join table',exact:false}).isDisabled(),true);
  await page.locator('#join-name').fill('Lantern Friend');await page.screenshot({path:path.join(out,'join-name.png')});
  await page.getByRole('button',{name:'Join table',exact:false}).click();
  await page.locator('.room-code').waitFor();assert.equal((await page.locator('.room-code').innerText()).trim(),code);
  assert.ok([...rooms.values()][0].players['home-invitation-guest'].name==='Lantern Friend');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('arctic-play.v1.profile')).name),'Lantern Friend');
  assert.ok(await page.evaluate(code=>JSON.parse(localStorage.getItem('arctic-play.v1.rooms'))[code].session.seatToken.length===64,code));checks.push('Submitting the name joins the real room service and saves the authenticated seat');
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(out,'report.json'),JSON.stringify({version:'4.9.0',checks,errors,actualRoomService:true,physicalAndroidTested:false},null,2)+'\n');
  checks.forEach(c=>console.log('PASS',c));
}finally{await context.close();await browser.close();for(const ws of sockets.clients)ws.terminate();service.close();await new Promise(resolve=>sockets.close(resolve));await new Promise(resolve=>server.close(resolve));}
