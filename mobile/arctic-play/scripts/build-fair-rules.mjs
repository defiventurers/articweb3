import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
export async function buildFairRules({build,root,mobile}) {
  const banner='// Generated by mobile/arctic-play/scripts/build-web.mjs. Do not edit; imports canonical Heritage Arcade rules.\nif (!globalThis.crypto) globalThis.crypto = require("node:crypto").webcrypto;';
  await build({input:path.join(mobile,'src/games.ts'),platform:'node',output:{file:path.join(root,'server/arcticPlayEngine.cjs'),format:'cjs',minify:false,banner}});
  const files=[];
  async function walk(folder) {
    for(const entry of await fs.readdir(folder,{withFileTypes:true})) {
      const file=path.join(folder,entry.name);
      if(entry.isDirectory()) await walk(file);
      else if(/\.(js|ts|json)$/.test(file)&&!/(test|spec)\./.test(file)) files.push(file);
    }
  }
  await walk(path.join(root,'frontend/src/games'));
  for(const name of ['games.ts','dominion.js','dominionTeams.js']) files.push(path.join(mobile,'src',name));
  files.push(path.join(root,'server/gameRules.js'));
  const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
  const source=[];
  for(const file of files.sort()) source.push({path:path.relative(root,file).split(path.sep).join('/'),sha256:hash(await fs.readFile(file))});
  const manifest={protocol:'ak-fair-play-v1',rulesHash:hash(JSON.stringify(source)),engineHash:hash(await fs.readFile(path.join(root,'server/arcticPlayEngine.cjs'))),source};
  await fs.writeFile(path.join(root,'shared/fair-play/rules-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  return manifest;
}
