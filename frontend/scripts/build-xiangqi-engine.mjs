import { build } from "rolldown";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const destination = new URL("../../server/xiangqiEngine.cjs", import.meta.url);
const result = await build({
  input: fileURLToPath(new URL("src/games/xiangqi/engine.ts", root)),
  platform: "node", write: false,
  output: { format: "cjs", sourcemap: false, banner: "// Generated by frontend/scripts/build-xiangqi-engine.mjs. Do not edit by hand." },
});
const code = result.output.find(item => item.type === "chunk").code;
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== code) throw new Error("Xiangqi server engine is stale. Run npm run build:xiangqi-engine in frontend.");
  console.log("Xiangqi browser and server engine sources match.");
} else { await writeFile(destination, code); console.log("Built shared Xiangqi server engine."); }
